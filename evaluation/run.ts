import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { performance } from 'node:perf_hooks';
import { corpus, examples, templateDraft, keywordCategory, DATASET_VERSION } from './dataset.js';
import { keyword, cosine, rank, RANK_VERSION } from '../server/retrieval/rank.js';
import { draftChecks, retrievalMetrics, percentile } from './metrics.js';
import { makeProvider } from '../server/ai/provider.js';
import { estimatedCost } from '../server/ai/service.js';
import { config } from '../server/config.js';
import { embeddingText } from '../server/complaints.js';
import { PROMPT_VERSION, SCHEMA_VERSION } from '../server/ai/prompts.js';
const live = process.argv.includes('--live'),
  provider = live ? makeProvider() : null;
if (live && !provider) {
  console.error(
    'UNVERIFIED: live evaluation requires OPENAI_API_KEY. No mock vectors or draft outputs were substituted.',
  );
  process.exit(2);
}
const vectors = new Map<string, number[]>(),
  embeddingLatencies: number[] = [],
  rankingLatencies: number[] = [],
  costs: number[] = [],
  errors: { example: string; outcome: string }[] = [];
await mkdir('evaluation/results', { recursive: true });
await mkdir('evaluation/cache', { recursive: true });
// Cache only actual provider results, keyed by model, dimensions, preprocessing and input; never generate mock embeddings.
async function embed(text: string) {
  if (vectors.has(text)) return vectors.get(text)!;
  const prepared = embeddingText({
    title: text.slice(0, 100),
    description: text,
    category: 'roads',
  });
  const hash = createHash('sha256')
      .update(
        JSON.stringify([
          config.EMBEDDING_MODEL,
          config.EMBEDDING_DIMENSIONS,
          'embedding-text-v1',
          prepared,
        ]),
      )
      .digest('hex'),
    path = `evaluation/cache/${hash}.json`;
  try {
    const cached = JSON.parse(await readFile(path, 'utf8'));
    if (
      cached.source !== 'live-openai' ||
      cached.input !== prepared ||
      cached.dimensions !== config.EMBEDDING_DIMENSIONS ||
      !Array.isArray(cached.vector) ||
      cached.vector.length !== config.EMBEDDING_DIMENSIONS ||
      cached.vector.some((n: unknown) => typeof n !== 'number' || !Number.isFinite(n))
    )
      throw new Error('Invalid embedding cache entry');
    vectors.set(text, cached.vector);
    return cached.vector as number[];
  } catch {}
  const start = performance.now(),
    r = await provider!.embed(prepared);
  embeddingLatencies.push(performance.now() - start);
  costs.push(estimatedCost('embedding', r.usage));
  await writeFile(
    path,
    JSON.stringify({
      model: r.model,
      dimensions: r.value.length,
      vector: r.value,
      usage: r.usage,
      generatedAt: new Date().toISOString(),
      source: 'live-openai',
      input: prepared,
    }),
  );
  vectors.set(text, r.value);
  return r.value;
}
if (provider) {
  console.log('Live evaluation: provider calls may incur charges; inputs are synthetic.');
  for (const text of new Set([
    ...corpus.map((c) => c.incident.text),
    ...examples.map((e) => e.query.text),
  ])) {
    try {
      await embed(text);
    } catch (e) {
      errors.push({ example: 'embedding', outcome: (e as Error).name });
      break;
    }
  }
}
const semanticReady = !!provider && !errors.length;
type Strategy = 'keyword' | 'embedding' | 'hybrid';
function ranked(e: (typeof examples)[number], strategy: Strategy) {
  return corpus
    .filter((c) => c.split === e.split)
    .map((c) => {
      const similarity =
        strategy === 'keyword'
          ? keyword(e.query.text, c.incident.text)
          : cosine(vectors.get(e.query.text)!, vectors.get(c.incident.text)!);
      const signals = rank(e.query, c.incident, similarity);
      return {
        id: c.id,
        score: strategy === 'hybrid' ? signals.score : similarity,
        eligible: strategy === 'hybrid' ? signals.eligible : true,
        similarity,
      };
    })
    .filter((c) => c.similarity > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 5);
}
const strategies: Strategy[] = semanticReady ? ['keyword', 'embedding', 'hybrid'] : ['keyword'];
const output: Record<string, unknown> = {
  version: DATASET_VERSION,
  generatedAt: new Date().toISOString(),
  mode: live ? 'live-provider' : 'offline-deterministic',
  provenance: 'All examples are synthetic, generated by code. Human review pending.',
  groups: { development: 20, test: 10 },
  examples: { development: 160, test: 80, corpus: 120 },
  splitRule:
    'Incident groups assigned before report variants. Related candidates stay within the same split.',
  datasetSha256: createHash('sha256').update(JSON.stringify({ corpus, examples })).digest('hex'),
  promptVersion: PROMPT_VERSION,
  schemaVersion: SCHEMA_VERSION,
  rankVersion: RANK_VERSION,
  models: { draft: config.DRAFT_MODEL, embedding: config.EMBEDDING_MODEL },
  semanticStatus: semanticReady
    ? 'live exact cosine evaluated; Atlas unverified'
    : 'unverified — no live embeddings',
  errors,
};
const retrieval: Record<string, unknown> = {};
for (const strategy of strategies) {
  let best = { threshold: 0, f1: -1 };
  // Select threshold ONLY on development labels; freeze before accessing test metrics.
  for (let n = 1; n <= 19; n++) {
    const threshold = n / 20;
    const rows = examples
      .filter((e) => e.split === 'development')
      .map((e) => {
        const r = ranked(e, strategy);
        return {
          relevant: e.relevant,
          candidates: r.map((x) => x.id),
          suggestions: r.filter((x) => x.eligible && x.score >= threshold).map((x) => x.id),
        };
      });
    const m = retrievalMetrics(rows),
      p = m.precision ?? 0,
      r = m.recall ?? 0,
      f1 = p + r ? (2 * p * r) / (p + r) : 0;
    if (f1 > best.f1 || (f1 === best.f1 && threshold > best.threshold)) best = { threshold, f1 };
  }
  const rows = examples
    .filter((e) => e.split === 'test')
    .map((e) => {
      const start = performance.now(),
        r = ranked(e, strategy);
      rankingLatencies.push(performance.now() - start);
      return {
        example: e.id,
        scenario: e.scenario,
        relevant: e.relevant,
        candidates: r.map((x) => x.id),
        suggestions: r.filter((x) => x.eligible && x.score >= best.threshold).map((x) => x.id),
      };
    });
  retrieval[strategy] = {
    threshold: best.threshold,
    developmentF1: best.f1,
    test: retrievalMetrics(rows),
    failureExamples: rows
      .filter(
        (r) =>
          r.suggestions.some((id) => !r.relevant.includes(id)) ||
          r.relevant.some((id) => !r.suggestions.includes(id)),
      )
      .slice(0, 12),
    rows,
  };
}
output.retrieval = retrieval;
const draftResults: {
  id: string;
  checks: ReturnType<typeof draftChecks>;
  latencyMs: number;
  costUsd: number;
  source: string;
}[] = [];
for (const e of examples.filter((e) => e.split === 'test')) {
  let draft = templateDraft(e.report),
    cost = 0,
    start = performance.now();
  if (provider) {
    try {
      const r = await provider.draft(e.report);
      draft = r.value;
      cost = estimatedCost('draft', r.usage);
      costs.push(cost);
    } catch (error) {
      errors.push({ example: e.id, outcome: (error as Error).name });
      continue;
    }
  }
  draftResults.push({
    id: e.id,
    checks: draftChecks(draft, e),
    latencyMs: performance.now() - start,
    costUsd: cost,
    source: provider ? 'live-provider' : 'fixed-template',
  });
}
const sum = (key: keyof ReturnType<typeof draftChecks>) =>
  draftResults.reduce((n, r) => n + Number(r.checks[key]), 0);
output.drafting = {
  source: provider ? 'live-provider' : 'fixed-template baseline; AI drafting unverified',
  attempted: 80,
  completed: draftResults.length,
  factualPreservationProxy: sum('factChecks') ? sum('factsPreserved') / sum('factChecks') : null,
  unsupportedNumbers: sum('unsupportedNumbers'),
  unsupportedEvidence: sum('unsupportedEvidence'),
  missingInformationRecall: sum('missingExpected')
    ? sum('missingDetected') / sum('missingExpected')
    : null,
  extraQuestions: sum('extraQuestions'),
  latencyMs: {
    p50: percentile(
      draftResults.map((r) => r.latencyMs),
      0.5,
    ),
    p95: percentile(
      draftResults.map((r) => r.latencyMs),
      0.95,
    ),
  },
  estimatedCostUsd: draftResults.reduce((n, r) => n + r.costUsd, 0),
  limitation:
    'String checks are proxies: they do not establish factual correctness or detect all unsupported additions. Human rubric pending.',
  rows: draftResults,
};
output.categories = Object.fromEntries(
  ['roads', 'waste', 'water', 'streetlights', 'drainage'].map((cat) => {
    const rows = examples.filter((e) => e.split === 'test' && e.expectedCategory === cat),
      tp = rows.filter((e) => keywordCategory(e.query.text) === cat).length,
      fp = examples.filter(
        (e) =>
          e.split === 'test' && e.expectedCategory !== cat && keywordCategory(e.query.text) === cat,
      ).length;
    return [
      cat,
      {
        source: 'keyword baseline',
        support: rows.length,
        precision: tp + fp ? tp / (tp + fp) : null,
        recall: tp / rows.length,
        liveDraftAccuracy: provider
          ? draftResults.filter((r) => rows.some((e) => e.id === r.id) && r.checks.categoryCorrect)
              .length / (draftResults.filter((r) => rows.some((e) => e.id === r.id)).length || 1)
          : null,
      },
    ];
  }),
);
output.operations = {
  rankingLatencyMs: {
    p50: percentile(rankingLatencies, 0.5),
    p95: percentile(rankingLatencies, 0.95),
  },
  embeddingProviderLatencyMs: {
    p50: percentile(embeddingLatencies, 0.5),
    p95: percentile(embeddingLatencies, 0.95),
  },
  estimatedCostUsd: costs.reduce((a, b) => a + b, 0),
  pricing:
    'Configured per-million token rates. Cached embeddings incur zero additional provider cost in this run. Retry charges may not appear in usage.',
  humanReview: 'pending',
  modelGrading: 'not used',
};
const path = `evaluation/results/${live ? 'live' : 'offline'}.json`;
await writeFile(path, JSON.stringify(output, null, 2) + '\n');
console.log(
  `Wrote actual ${live ? 'live' : 'offline'} measurements to ${path}. Semantic status: ${output.semanticStatus}`,
);
